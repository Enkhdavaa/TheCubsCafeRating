import { Client } from "@db/postgres";

const databaseUrl = withDatabaseName(
  Deno.env.get("DATABASE_URL") ??
    "postgresql://enkhdavaabatlkhagva@localhost:5432/enkhdavaabatlkhagva"
);

// Logged once so the deploy logs show where the app connects (never the password).
console.log(`Database: ${describeTarget(databaseUrl)}`);

// Tables are created on first use, so a new or newly attached database works
// without a separate migration step. Safe to run repeatedly.
let tablesReady: Promise<unknown> | undefined;

function createTables(connection: Client) {
  return connection.queryArray`
    CREATE TABLE IF NOT EXISTS CafeRating (
      Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      Username TEXT NOT NULL,
      Cafe TEXT NOT NULL,
      Product TEXT NOT NULL,
      Score SMALLINT NOT NULL CHECK (Score BETWEEN 1 AND 10)
    );
  `;
}

// Opens a fresh connection for each call and always closes it afterwards.
// Long-lived pooled connections break when the database closes them (idle
// timeouts, restarts), and the driver can't recover from a broken pipe, so
// every later query would fail until the server restarts.
export async function withConnection<T>(
  run: (connection: Client) => Promise<T>
): Promise<T> {
  const connection = new Client(databaseUrl);
  await connection.connect();
  try {
    tablesReady ??= createTables(connection).catch((err) => {
      tablesReady = undefined; // Try again on the next request
      throw err;
    });
    await tablesReady;
    return await run(connection);
  } finally {
    await connection.end().catch(() => {});
  }
}

// Prisma Postgres connection strings (as provided by Deno Deploy) leave out the
// database name: ".../?sslmode=require". psql and node-postgres fill in a
// default, but this driver refuses to connect without one, so use "postgres"
// like Prisma's own examples do.
function withDatabaseName(url: string): string {
  try {
    if (new URL(url).pathname.length > 1 || Deno.env.get("PGDATABASE")) {
      return url;
    }
  } catch {
    return url;
  }
  return url.replace(/\/?(?=[?#]|$)/, "/postgres");
}

function describeTarget(url: string): string {
  const timeline = Deno.env.get("DENO_TIMELINE") ?? "local";
  const pgDatabase = Deno.env.get("PGDATABASE");
  try {
    const { hostname, port, pathname } = new URL(url);
    const database = pathname.slice(1) || "(none in URL)";
    return `${hostname}:${port || 5432}, database ${database}, PGDATABASE ${
      pgDatabase ?? "(not set)"
    }, timeline ${timeline}`;
  } catch {
    return `DATABASE_URL could not be parsed, timeline ${timeline}`;
  }
}
