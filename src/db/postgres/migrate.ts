import { withConnection } from "./dbAccess.ts";

// Creates the tables the app needs. Safe to run repeatedly.
// Deno Deploy runs this before every deploy ("predeploy" in deno.json),
// against the database of the timeline being deployed.
await withConnection(
  (connection) => connection.queryArray`
    CREATE TABLE IF NOT EXISTS CafeRating (
      Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      Username TEXT NOT NULL,
      Cafe TEXT NOT NULL,
      Product TEXT NOT NULL,
      Score SMALLINT NOT NULL CHECK (Score BETWEEN 1 AND 10)
    );
  `
);
console.log("Migration complete: CafeRating table is ready.");
